import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(
  repoRoot,
  'docs',
  'architecture',
  'tech',
  'TECH-api-specification.md',
);
const checkOnly = process.argv.includes('--check');

const surfaces = [
  {
    name: 'App API',
    key: 'app',
    prefix: '/app/v3/api',
    expectedCount: 127,
    auth: '`Authorization` and `Access-Token` through the global app session',
    sdk: '`@sdkwork/agents-app-sdk` and `sdkwork_agents_app_sdk`',
    source:
      'crates/sdkwork-intelligence-agents-service/specs/openapi/agents-app-api.openapi.yaml',
  },
  {
    name: 'Backend API',
    key: 'backend',
    prefix: '/backend/v3/api',
    expectedCount: 60,
    auth: '`Authorization` and `Access-Token` for operator context',
    sdk: '`@sdkwork/agents-backend-sdk`',
    source:
      'crates/sdkwork-intelligence-agents-service/specs/openapi/agents-backend-api.openapi.yaml',
  },
  {
    name: 'Open API',
    key: 'open',
    prefix: '/agent/v3/api',
    expectedCount: 56,
    auth: '`X-API-Key`',
    sdk: '`@sdkwork/agents-sdk`',
    source:
      'crates/sdkwork-intelligence-agents-service/specs/openapi/agents-open-api.openapi.yaml',
  },
];

const httpMethods = ['get', 'post', 'put', 'patch', 'delete', 'options', 'head'];

for (const surface of surfaces) {
  const sourcePath = path.join(repoRoot, surface.source);
  const document = YAML.parse(fs.readFileSync(sourcePath, 'utf8'));
  surface.operations = [];
  for (const [routePath, pathItem] of Object.entries(document.paths ?? {})) {
    if (!routePath.startsWith(surface.prefix)) {
      throw new Error(`${surface.name} path is outside ${surface.prefix}: ${routePath}`);
    }
    for (const method of httpMethods) {
      const operation = pathItem?.[method];
      if (!operation) continue;
      if (!operation.operationId) {
        throw new Error(`${surface.name} ${method.toUpperCase()} ${routePath} has no operationId`);
      }
      surface.operations.push({
        method: method.toUpperCase(),
        path: routePath,
        operationId: operation.operationId,
        summary: operation.summary ?? '',
      });
    }
  }
  if (surface.operations.length !== surface.expectedCount) {
    throw new Error(
      `${surface.name} operation count mismatch: expected ${surface.expectedCount}, got ${surface.operations.length}`,
    );
  }
}

const rendered = renderDocument(surfaces);
if (checkOnly) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
  if (normalize(current) !== normalize(rendered)) {
    throw new Error(
      'Agents API documentation is stale. Run node scripts/generate-agents-api-docs.mjs.',
    );
  }
  console.log('Agents API documentation is current.');
} else {
  fs.writeFileSync(outputPath, rendered, 'utf8');
  console.log(`Generated ${path.relative(repoRoot, outputPath)}.`);
}

function renderDocument(apiSurfaces) {
  const total = apiSurfaces.reduce(
    (sum, surface) => sum + surface.operations.length,
    0,
  );
  const lines = [
    '# SDKWork Agents HTTP API Specification',
    '',
    '<!-- Generated by scripts/generate-agents-api-docs.mjs from authored OpenAPI. -->',
    '',
    '- Version: `6.0.0`',
    '- Status: active',
    `- Total operations: ${total}`,
    '- Domain model: `AgentWorkspace -> AgentProject -> AgentSession -> AgentTurn -> AgentSessionItem -> AgentInteraction`',
    '',
    '## 1. Authorities',
    '',
    'The authored OpenAPI documents are the contract authorities. This document is a',
    'deterministic inventory and must be regenerated after an authority change.',
    '',
    '| Surface | Prefix | Operations | Authentication | Consumer SDK |',
    '| --- | --- | ---: | --- | --- |',
    ...apiSurfaces.map(
      (surface) =>
        `| ${surface.name} | \`${surface.prefix}\` | ${surface.operations.length} | ${surface.auth} | ${surface.sdk} |`,
    ),
    '',
    '## 2. Common Contract',
    '',
    '- Tenant, organization and user scope come from trusted request context; callers do not send scope selectors.',
    '- JSON success uses `SdkWorkApiResponse` with numeric `code: 0`, typed `data` and server-owned `traceId`.',
    '- Errors use RFC 9457 `application/problem+json` with numeric `code` and `traceId`.',
    '- Offset lists use `page` and `page_size`; cursor lists use an opaque `cursor` and `page_size`. `page_size` is at most 200 and list results include mode-specific `PageInfo`.',
    '- Create Session and Turn commands are idempotent through `idempotencyKey`, `payloadHash` and `requestedAt`.',
    '- Optimistic mutations use `expectedVersion`; delete success is HTTP 204 without a JSON body.',
    '- Turn SSE uses typed `AgentTurnStreamEvent` values. A terminal `completion` event contains `AgentTurnExecutionResponse`.',
    '- Session Items are Agents execution facts. They do not carry IM delivery, read or presence semantics.',
    '',
    '## 3. SDK Consumption',
    '',
    'TypeScript consumers import only package roots. App consumers construct',
    '`createClient({ baseUrl: "https://host", tokenManager })`; the composed',
    'package accepts a common SDK root or one canonical `/app/v3/api` surface URL',
    'and normalizes the surface prefix exactly once. Non-streaming',
    'Turn execution uses `completeAgentTurn(...)`; streaming uses',
    '`client.ai.turns.stream(...)`.',
    '',
    'Flutter consumers depend on package `sdkwork_agents_app_sdk` and import',
    '`package:sdkwork_agents_app_sdk/sdkwork_agents_app_sdk.dart`. The generated',
    'client exposes `agentsSessions*`, `agentsTurns*`, `agentsSessionItems*`,',
    '`agentsItemFeedback*` and `agentsInteractions*` methods.',
    '',
    '## 4. Complete Operation Inventory',
    '',
  ];

  for (const surface of apiSurfaces) {
    lines.push(`### 4.${apiSurfaces.indexOf(surface) + 1} ${surface.name}`);
    lines.push('');
    lines.push(`Authority: [${path.basename(surface.source)}](../../../${surface.source})`);
    lines.push('');
    lines.push('| # | Method | Path | Operation ID | Summary |');
    lines.push('| ---: | --- | --- | --- | --- |');
    surface.operations.forEach((operation, index) => {
      lines.push(
        `| ${index + 1} | ${operation.method} | \`${escapeCell(operation.path)}\` | \`${escapeCell(operation.operationId)}\` | ${escapeCell(operation.summary)} |`,
      );
    });
    lines.push('');
  }

  lines.push('## 5. Verification');
  lines.push('');
  lines.push('```powershell');
  lines.push('node scripts/generate-agents-api-docs.mjs --check');
  lines.push('node ../sdkwork-specs/tools/check-api-response-envelope.mjs --workspace .');
  lines.push('node ../sdkwork-specs/tools/check-api-operation-patterns.mjs --workspace .');
  lines.push('node ../sdkwork-specs/tools/check-route-path-collisions.mjs --workspace .');
  lines.push('node ../sdkwork-specs/tools/check-pagination.mjs --workspace .');
  lines.push('node scripts/check-agent-sdk-workspace.mjs');
  lines.push('```');
  lines.push('');
  return `${lines.join('\n')}\n`;
}

function escapeCell(value) {
  return String(value).replaceAll('|', '\\|').replaceAll(/\s+/gu, ' ').trim();
}

function normalize(value) {
  return value.replaceAll('\r\n', '\n').trimEnd();
}
